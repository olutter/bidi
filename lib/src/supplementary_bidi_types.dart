final _supplementaryBidiBytes = base64Decode(_supplementaryBidiBase64);

CharacterType _getSupplementaryCharacterType(int character) {
  final data = _supplementaryBidiBytes;
  var left = 0;
  var right = data.length ~/ 7 - 1;
  while (left <= right) {
    final middle = (left + right) ~/ 2;
    final offset = middle * 7;
    final start =
        (data[offset] << 16) | (data[offset + 1] << 8) | data[offset + 2];
    final end =
        (data[offset + 3] << 16) | (data[offset + 4] << 8) | data[offset + 5];
    if (character < start) {
      right = middle - 1;
    } else if (character > end) {
      left = middle + 1;
    } else {
      return CharacterType.values[data[offset + 6]];
    }
  }
  return CharacterType.ltr;
}
